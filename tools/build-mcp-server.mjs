import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const packageJsonPath = require.resolve("@microsoft/spe-mcp/package.json");
const packageRoot = dirname(packageJsonPath);
const outputRoot = join(root, "out", "mcp");
const outputDist = join(outputRoot, "dist");
const launcherPath = join(outputRoot, "launcher.cjs");

await mkdir(outputDist, { recursive: true });

await build({
    entryPoints: [join(packageRoot, "dist", "cli.js")],
    outfile: join(outputDist, "cli.js"),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    banner: {
        js: "import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);"
    },
    legalComments: "none"
});

const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
await writeFile(
    join(outputRoot, "package.json"),
    `${JSON.stringify({
        name: packageJson.name,
        version: packageJson.version,
        type: "module"
    }, null, 2)}\n`
);

await writeFile(
    launcherPath,
    [
        "/* Generated by tools/build-mcp-server.mjs. */",
        "// Commander otherwise detects VS Code's Electron runtime and treats argv[1]",
        "// as a user argument instead of the script path.",
        "delete process.versions.electron;",
        "void import('./dist/cli.js');",
        "",
    ].join("\n")
);

for (const asset of ["samples", "LICENSE", "THIRD-PARTY-NOTICES"]) {
    await cp(join(packageRoot, asset), join(outputRoot, asset), { recursive: true });
}
